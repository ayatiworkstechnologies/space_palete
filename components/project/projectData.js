export function getImagePanelSize(image) {
  const fileName = image.split("/").pop();
  const dimensions = projectImageDimensions[fileName];

  if (dimensions) {
    const [sourceWidth, sourceHeight] = dimensions;
    const sourceRatio = sourceWidth / sourceHeight;
    const height = 600;
    const naturalDisplayWidth = Math.round(height * sourceRatio);
    const width =
      sourceRatio >= 1.45
        ? 900
        : sourceRatio >= 0.92
          ? Math.max(600, naturalDisplayWidth)
          : naturalDisplayWidth;
    const ratio = Number((width / height).toFixed(3));
    const shouldCrop = width / height < sourceRatio;

    return {
      className: "h-[62vh] w-[calc(62vh*var(--image-ratio))] md:h-[72vh] md:w-[calc(72vh*var(--image-ratio))]",
      sizes: `(max-width: 768px) calc(62vh * ${ratio}), calc(72vh * ${ratio})`,
      width,
      height,
      ratio,
      sourceWidth,
      sourceHeight,
      sourceRatio: Number(sourceRatio.toFixed(3)),
      imageClassName: shouldCrop ? "object-cover" : "object-contain",
      style: {
        "--image-ratio": ratio,
        aspectRatio: `${width} / ${height}`,
      },
    };
  }

  if (wideProjectImages.has(fileName)) {
    return {
      className: "h-[62vh] aspect-[16/9] md:h-[72vh]",
      sizes: "(max-width: 768px) 110vh, 128vh",
      width: 16,
      height: 9,
      ratio: 16 / 9,
      imageClassName: "object-cover",
      style: undefined,
    };
  }

  if (portraitProjectImages.has(fileName)) {
    return {
      className: "h-[62vh] aspect-[3/4] md:h-[72vh]",
      sizes: "(max-width: 768px) 47vh, 54vh",
      width: 3,
      height: 4,
      ratio: 3 / 4,
      imageClassName: "object-contain",
      style: undefined,
    };
  }

  return {
    className: "h-[62vh] aspect-[4/3] md:h-[72vh]",
    sizes: "(max-width: 768px) 83vh, 96vh",
    width: 4,
    height: 3,
    ratio: 4 / 3,
    imageClassName: "object-contain",
    style: undefined,
  };
}

export function getProjectBySlug(slug) {
  return projectEntries.find((project) => project.slug === slug);
}

export function getNextProject(slug) {
  const currentIndex = projectEntries.findIndex((project) => project.slug === slug);

  if (currentIndex === -1 || projectEntries.length <= 1) {
    return null;
  }

  return projectEntries[(currentIndex + 1) % projectEntries.length];
}
